export function getCategoryImages(productSlug, categorySlug) {
  if (!productSlug || !categorySlug) return [];
  const productCats = categoryImageMap[productSlug];
  if (!productCats) return [];
  return productCats[categorySlug] || [];
}

export function getAllCategoryImages(productSlug) {
  if (!productSlug) return [];
  const productCats = categoryImageMap[productSlug];
  if (!productCats) return [];
  const result = [];
  for (const catSlug of Object.keys(productCats)) {
    for (let i = 0; i < (productCats[catSlug] || []).length; i++) {
      result.push({
        categorySlug: catSlug,
        url: productCats[catSlug][i],
        imageIndex: i,
      });
    }
  }
  return result;
}
